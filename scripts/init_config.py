"""Generate installation configuration without touching existing data or credentials."""

from __future__ import annotations

import argparse
import base64
import os
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(mode: str) -> str:
    master = base64.urlsafe_b64encode(secrets.token_bytes(32)).decode()
    jwt = secrets.token_urlsafe(48)
    password = secrets.token_hex(24)
    root_password = secrets.token_hex(24)
    database = (
        f"mysql+asyncmy://docsync:{password}@mysql:3306/docsync?charset=utf8mb4"
        if mode == "docker"
        else "sqlite+aiosqlite:///./data/docsync.db"
    )
    return "\n".join(
        [
            "# Generated by docsync. Keep this file private and backed up.",
            "DOCSYNC_ENV=prod",
            "DOCSYNC_DEBUG=false",
            f"DOCSYNC_MASTER_KEY={master}",
            f"DOCSYNC_JWT_SECRET={jwt}",
            f"DOCSYNC_META_DB_URL={database}",
            "DOCSYNC_DATA_DIR=./data",
            "DOCSYNC_SCHEDULER_ENABLED=true",
            "DOCSYNC_EMBEDDED_SCHEDULER=true",
            "DOCSYNC_WORKER_MAX_CONCURRENCY=2",
            "DOCSYNC_CORS_ORIGINS=[]",
            "WEB_PORT=8090",
            f"MYSQL_PASSWORD={password}",
            f"MYSQL_ROOT_PASSWORD={root_password}",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=["docker", "manual"], default="docker")
    parser.add_argument("--output", type=Path, help="New installation configuration path")
    args = parser.parse_args(argv)
    destination = args.output or (ROOT / ".env")
    destination.parent.mkdir(parents=True, exist_ok=True)
    try:
        fd = os.open(destination, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        print(f"Configuration already exists; preserved: {destination}")
        return 1
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(generate(args.mode))
    print(f"Created {args.mode} configuration: {destination}")
    print("Next: follow README.md to initialize the database and administrator.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
